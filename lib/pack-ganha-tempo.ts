export function matchPackAssetsForScene(sceneText: string, assetType?: string, limit: number = 3): PackAssetItem[] {
  const textLower = (sceneText || '').toLowerCase();
  const scored: Array<{ item: PackAssetItem; score: number }> = [];

  for (const item of PACK_GANHA_TEMPO_ITEMS) {
    let score = 0;

    // Match por palavras-chave
    for (const kw of item.keywords) {
      if (textLower.includes(kw)) {
        score += 3;
      }
    }

    // Match por tipo de asset da cena
    if (assetType) {
      const at = assetType.toLowerCase();
      if (at === 'vídeo' && item.mimeType.startsWith('video/')) score += 1;
      if (at === 'imagem' && item.mimeType.startsWith('image/')) score += 1;
      if (at === 'texto' && (item.category.includes('Graficos') || item.category.includes('Icones'))) score += 2;
    }

    if (score > 0) {
      scored.push({ item, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);

  if (scored.length > 0) {
    return scored.slice(0, limit).map((s) => s.item);
  }

  // Fallback geral contextual
  const isVideo = assetType?.toLowerCase() === 'vídeo';
  const defaultItems = isVideo
    ? PACK_GANHA_TEMPO_ITEMS.filter((i) => i.category.includes('Graficos') || i.category.includes('Efeitos_Sonoros'))
    : PACK_GANHA_TEMPO_ITEMS.filter((i) => i.category.includes('Icones') || i.category.includes('Graficos'));

  return defaultItems.slice(0, limit);
}
